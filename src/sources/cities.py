RETIRED_CITIES = dict(_RETIRED)

_EARTH_RADIUS_KM = 6371


def city_name(code):
    """三字码 → 中文城市名；不在注册表（含已下线城市）返回 None。"""
    entry = CITIES.get(code)
    return entry["name"] if entry else None


def airport_name(code):
    """三字码 → 机场全称；不在注册表返回 None。"""
    entry = CITIES.get(code)
    return entry["airport"] if entry else None


def is_retired(code):
    """是否为 v1.4 已下线城市码。"""
    return code in RETIRED_CITIES


def retired_name(code):
    """已下线城市码 → 原中文名；未下线或未知返回 None。"""
    return RETIRED_CITIES.get(code)


def all_cities():
    """全部城市（注册表顺序），供下拉与 CLI 提示使用；每城含机场全称。"""
    return [{"code": code, "name": entry["name"], "airport": entry["airport"]}
            for code, entry in CITIES.items()]


def distance_km(origin, destination):
    """两城大圆距离（km，向上取整到整数）；任一城市码不在注册表返回 None。"""
    a, b = CITIES.get(origin), CITIES.get(destination)
    if not a or not b:
        return None
    lat1, lon1 = math.radians(a["lat"]), math.radians(a["lon"])
    lat2, lon2 = math.radians(b["lat"]), math.radians(b["lon"])
    dlat, dlon = lat2 - lat1, lon2 - lon1
    h = math.sin(dlat / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2) ** 2
    return int(round(2 * _EARTH_RADIUS_KM * math.asin(math.sqrt(h))))
